"""流れの各段階（準備・網羅・様式・提出・専用様式）と、v0.2 で広げた抽出のテスト。"""
import json
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from test_banto import ProjectCase, _run, _set_cell, _w  # noqa: E402
from banto import engine, fio  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "examples"))


class FlowTest(ProjectCase):
    def cov(self, res, iid):
        return next(c for c in res.coverage if c.id == iid)

    # ------------------------------------------------------------ 抽出の拡張
    def test_ddl_defaults_comments_decimal_indexes(self):
        _w(self.p, "db/a.sql", """CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(30) NOT NULL DEFAULT 'guest' COMMENT '氏名',
  price DECIMAL(10,2) DEFAULT 0,
  email VARCHAR(100),
  team_id INTEGER
) COMMENT='利用者';
CREATE INDEX users_name_email ON users (name, email);
CREATE TABLE teams (id INTEGER PRIMARY KEY, title VARCHAR(50));
""")
        src = {s.id: s for s in engine.extract_all(self.p)["tables"]}["ddl-a"]
        u = src.containers["users"]
        self.assertEqual(u.items["id"].attrs["default"].value, "")            # BY DEFAULT AS IDENTITY は初期値ではない
        self.assertEqual(u.items["name"].attrs["default"].value, "guest")
        self.assertEqual(u.items["name"].attrs["logical_name"].value, "氏名")
        self.assertEqual((u.items["price"].attrs["length"].value, u.items["price"].attrs["scale"].value), (10, 2))
        self.assertEqual(u.attrs["title"].value, "利用者")
        self.assertEqual(u.attrs["indexes"].value, "(name, email)")

    def test_design_doc_by_headers(self):
        _w(self.p, "docs/design.md", """# 設計書

#### 利用者（users）
| No | 論理名 | 物理名 | データ型 | 桁数 | NOT NULL | PK | 初期値 | 備考 |
|---|---|---|---|---|---|---|---|---|
| 1 | 利用者ID | id | INTEGER | | ○ | ○ | | |
| 2 | 氏名 | name | VARCHAR | 30 | ○ | | | 姓名 |
| 3 | メール | email | VARCHAR | 100 | | | | |
| 4 | チーム | team_id | INTEGER | | | | | |
""")
        src = {s.id: s for s in engine.extract_all(self.p)["tables"]}["doc"]
        u = src.containers["users"]
        self.assertEqual(u.attrs["title"].value, "利用者")
        self.assertEqual(u.items["name"].attrs["logical_name"].value, "氏名")
        self.assertEqual(u.items["name"].attrs["length"].value, 30)
        self.assertFalse(u.items["name"].attrs["nullable"].value)
        self.assertTrue(u.items["id"].attrs["pk"].value)
        self.assertEqual(u.items["name"].attrs["description"].value, "姓名")

    def test_human_written_value_persists_without_drift(self):
        self.sync()
        _set_cell(os.path.join(self.p, "banto/design/detail/tables/users.md"), "`email`", "論理名", "メールアドレス")
        res = self.sync()
        self.assertEqual(res.ledgers["tables"]["users"].items["email"].values["logical_name"], "メールアドレス")
        self.assertIsNone(self.drift(res, "users", "email", "logical_name"))

    # ------------------------------------------------------------ 準備（役割）
    def test_roles(self):
        self.assertEqual(_run("--project", self.p, "init", "--judge", "田中", "--approver", "鈴木")[0], 0)
        res = self.sync()
        d = self.drift(res, "users", "email", "length")
        code, out = _run("--project", self.p, "decide", d.id, "--set", "100", "--by", "佐藤", "--reason", "x")
        self.assertNotEqual(code, 0)
        self.assertIn("判断者", out)
        self.assertEqual(_run("--project", self.p, "decide", d.id, "--set", "100", "--by", "田中", "--reason", "x")[0], 0)

    # ------------------------------------------------------------ 網羅
    def test_coverage_candidates_exclude_and_fill(self):
        res = self.sync()
        self.assertEqual(self.cov(res, "BD-07").applicability, "不要の候補")      # 帳票ライブラリなし
        self.assertEqual(self.cov(res, "BD-01").sufficiency, "情報不足")
        self.assertTrue(os.path.exists(os.path.join(self.p, "banto/manual/BD-01.md")))  # ひな形
        tdc = self.cov(res, "TD-02")
        self.assertEqual(tdc.sufficiency, "情報不足")
        self.assertTrue(any("論理名" in x for x in tdc.details))
        code, out = _run("--project", self.p, "decide", "--item", "BD-07", "--exclude", "--by", "t", "--reason", "帳票の要件なし")
        self.assertEqual(code, 0, out)
        p = os.path.join(self.p, "banto/manual/BD-01.md")
        fio.write(p, fio.read(p).replace("<!-- 書くこと", "利用者とチームを管理するシステム。対象はユーザー登録と検索。\n<!-- 書くこと"))
        res = self.sync()
        self.assertEqual(self.cov(res, "BD-07").applicability, "不要（判断済み）")
        self.assertEqual(self.cov(res, "BD-01").sufficiency, "充足")
        self.assertIn("BD-07", fio.read(os.path.join(self.p, "banto/coverage/README.md")))

    # ------------------------------------------------------------ 出力と提出
    def test_standard_export_and_release(self):
        import openpyxl
        _run("--project", self.p, "init", "--approver", "鈴木", "--judge", "田中")
        code, out = _run("--project", self.p, "export")
        self.assertEqual(code, 0, out)
        ex = os.path.join(self.p, "banto/export")
        for name in ("BD_基本設計書.xlsx", "DD_詳細設計書.xlsx", "TD_テーブル定義書.xlsx", "TS_テスト仕様書.xlsx"):
            self.assertTrue(os.path.exists(os.path.join(ex, name)), name)
        wb = openpyxl.load_workbook(os.path.join(ex, "TD_テーブル定義書.xlsx"))
        self.assertIn("users", wb.sheetnames)
        code, out = _run("--project", self.p, "release", "TD", "--by", "鈴木", "--reason", "x")
        self.assertNotEqual(code, 0)                                           # 未判断が残っている
        code, out = _run("--project", self.p, "release", "TD", "--by", "田中", "--reason", "x", "--allow-open")
        self.assertNotEqual(code, 0)                                           # 承認者ではない
        code, out = _run("--project", self.p, "release", "TD", "--by", "鈴木", "--reason", "次版で解消", "--allow-open")
        self.assertEqual(code, 0, out)
        self.assertNotEqual(_run("--project", self.p, "release", "TD", "--by", "鈴木", "--reason", "x", "--allow-open")[0], 0)
        _set_cell(os.path.join(self.p, "banto/design/detail/tables/users.md"), "`email`", "論理名", "メール")
        code, out = _run("--project", self.p, "release", "TD", "--by", "鈴木", "--reason", "第2版", "--allow-open")
        self.assertEqual(code, 0, out)
        rel = fio.read(os.path.join(self.p, "banto/releases/TD-v2/RELEASE.md"))
        self.assertIn("users.email 論理名「」→「メール」", rel)

    # ------------------------------------------------------------ 専用様式
    def test_custom_format_flow(self):
        import openpyxl
        from make_customer_template import make
        tpl = os.path.join(self.p, "tpl.xlsx")
        make(tpl)
        code, out = _run("--project", self.p, "format", "read", tpl, "--name", "顧客A")
        self.assertEqual(code, 0, out)
        lay = json.loads(fio.read(os.path.join(self.p, "banto/format/顧客A/layout.json")))
        sheets = {s["sheet"]: s for s in lay["sheets"]}
        self.assertEqual(sheets["表紙"]["role"], "cover")
        self.assertEqual([f["cell"] for f in sheets["表紙"]["fields"]][:2], ["C5", "C6"])
        self.assertEqual(sheets["テーブル定義"]["tables"][0]["header_row"], 6)
        self.assertNotEqual(_run("--project", self.p, "format", "confirm", "--name", "顧客A", "--step", "mapping", "--by", "t")[0], 0)
        self.assertEqual(_run("--project", self.p, "format", "trial", "--name", "顧客A")[0], 0)
        self.assertEqual(_run("--project", self.p, "format", "confirm", "--name", "顧客A", "--step", "layout", "--by", "t")[0], 0)
        self.assertEqual(_run("--project", self.p, "format", "map", "--name", "顧客A", "--doc-id", "CTD")[0], 0)
        self.assertEqual(_run("--project", self.p, "format", "confirm", "--name", "顧客A", "--step", "mapping", "--by", "t")[0], 0)
        cfg = json.loads(fio.read(os.path.join(self.p, "banto/project.json")))
        self.assertIn("区分", cfg["extra_columns"]["tables"])
        cfg["format"] = "custom:顧客A"
        fio.write(os.path.join(self.p, "banto/project.json"), json.dumps(cfg, ensure_ascii=False))
        code, out = _run("--project", self.p, "export")
        self.assertEqual(code, 0, out)
        wb = openpyxl.load_workbook(os.path.join(self.p, "banto/export/CTD_顧客A.xlsx"))
        self.assertIn("users", wb.sheetnames)
        ws = wb["users"]
        self.assertEqual(ws["C3"].value, "users")
        rows = {ws[f"C{r}"].value: r for r in range(7, 12)}
        self.assertEqual(ws[f"D{rows['id']}"].value, "INTEGER")
        self.assertEqual(ws[f"G{rows['id']}"].value, "○")
        led = fio.read(os.path.join(self.p, "banto/design/detail/tables/users.md"))
        self.assertIn("区分", led.split("<!-- banto:items -->")[1].splitlines()[1])


if __name__ == "__main__":
    unittest.main()
