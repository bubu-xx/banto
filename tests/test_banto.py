def _w(base, rel, text):
    fio.write(os.path.join(base, rel), text)


def _set_cell(path, row_key, header, value):
    """台帳MDの表で、row_key を含む行の、見出し header の列を書き換える。"""
    text = fio.read(path)
    lines = text.splitlines()
    head = next(ln for ln in lines if ln.startswith("| ID |"))
    idx = [h.strip() for h in head.split("|")].index(header)
    n = next(i for i, ln in enumerate(lines) if row_key in ln)
    cells = lines[n].split("|")
    cells[idx] = f" {value} "
    lines[n] = "|".join(cells)
    fio.write(path, "\n".join(lines) + "\n")


def _run(*args):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            code = main(list(args))
        except SystemExit as e:
            code = e.code
            if isinstance(code, str):
                err.write(code)
                code = 1
    return code, out.getvalue() + err.getvalue()


class ProjectCase(unittest.TestCase):
    """架空のプロジェクトを一時フォルダに作る土台（テストそのものは持たない）。"""

    def setUp(self):
        self.p = tempfile.mkdtemp(prefix="banto-")
        _w(self.p, "db/a.sql", DDL_A)
        _w(self.p, "db/b.sql", DDL_B)
        _w(self.p, "docs/design.md", MD)
        _w(self.p, "src/main/java/x/User.java", JAVA)
        _w(self.p, "src/main/java/x/Team.java", JAVA_TEAM)
        _w(self.p, "src/test/java/x/UserTests.java", TEST_JAVA)
        _w(self.p, "docs/test-spec.md", SPEC)
        _w(self.p, "target/surefire-reports/TEST-x.UserTests.xml", SUREFIRE)
        _w(self.p, "banto/sources.json", json.dumps(SOURCES, ensure_ascii=False))
        if shutil.which("git"):
            subprocess.run(["git", "init", "-q", self.p], check=True)
            subprocess.run(["git", "-C", self.p, "add", "-A"], check=True)
            subprocess.run(["git", "-C", self.p, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "base"], check=True)

    def tearDown(self):
        shutil.rmtree(self.p, ignore_errors=True)

    def sync(self):
        return engine.sync(self.p)

    def drift(self, res, container, item, attr):
        return next((d for d in res.drifts if d.container == container and d.item == item
                     and d.attr is not None and d.attr.name == attr), None)

    def snapshot(self):
        out = {}
        for dp, _, fs in os.walk(os.path.join(self.p, "banto")):
            for f in fs:
                p = os.path.join(dp, f)
                with open(p, "rb") as fh:
                    out[os.path.relpath(p, self.p)] = fh.read()
        return out



class BantoTest(ProjectCase):
    # ------------------------------------------------------------ 抽出
    def test_extract(self):
        src = engine.extract_all(self.p)
        t = {s.id: s for s in src["tables"]}
        self.assertEqual(set(t["ddl-a"].containers), {"users", "teams"})
        self.assertEqual(set(t["doc"].containers), {"users"})
        u = t["ddl-b"].containers["users"].items
        self.assertTrue(u["id"].attrs["unsigned"].value)
        self.assertEqual(u["email"].attrs["length"].value, 200)
        self.assertEqual(t["ddl-a"].containers["users"].items["team_id"].attrs["fk"].value, "teams.id")
        j = t["jpa"].containers["users"].items
        self.assertFalse(j["name"].attrs["nullable"].value)            # @NotBlank
        self.assertEqual(j["team_id"].attrs["fk"].value, "teams.id")    # @ManyToOne
        self.assertNotIn("length", j["email"].attrs)                    # 長さは明示されていない
        ts = {s.id: s for s in src["tests"]}
        self.assertEqual(set(ts["junit"].containers["UserTests"].items), {"createsUser", "Validation#rejectsBlankName"})
        self.assertEqual(ts["surefire"].containers["UserTests"].items["Validation#rejectsBlankName"].attrs["result"].value, "fail")
        self.assertEqual(len(ts["spec"].containers["UserTests"].items), 3)

    # ------------------------------------------------------------ 同期
    def test_sync_is_idempotent_and_finds_drifts(self):
        res = self.sync()
        snap = self.snapshot()
        self.sync()
        self.assertEqual(snap, self.snapshot(), "同じ入力で2回同期したら、出力は同一であること")
        self.assertIsNotNone(self.drift(res, "users", "email", "length"))
        self.assertIsNotNone(self.drift(res, "teams", None, "exists"))          # 設計書に無い
        self.assertIsNotNone(self.drift(res, "UserTests", "Validation#rejectsLongName", "exists"))
        self.assertIsNone(self.drift(res, "users", "name", "length"))           # 全員一致
        ids = [d.id for d in res.drifts]
        self.assertEqual(len(ids), len(set(ids)))

    def test_ledger_roundtrip(self):
        res = self.sync()
        for dn in ("tables", "tests"):
            dom = get(dn)
            disk = LG.load_all(res.base, dom)
            for name, lc in res.ledgers[dn].items():
                self.assertEqual(lc.id, disk[name].id)
                for iname, it in lc.items.items():
                    self.assertEqual(it.values, disk[name].items[iname].values, f"{name}.{iname}")
                    self.assertEqual(it.exists, disk[name].items[iname].exists)

    # ------------------------------------------------------------ 判断
    def test_decide_set_then_fix_resolves(self):
        res = self.sync()
        d = self.drift(res, "users", "email", "length")
        code, out = _run("--project", self.p, "decide", d.id, "--set", "100", "--by", "t", "--reason", "設計どおり")
        self.assertEqual(code, 0, out)
        res = self.sync()
        d2 = self.drift(res, "users", "email", "length")
        self.assertEqual(d2.status, "decided")
        self.assertEqual(d2.deviating, ["ddl-b"])
        self.assertIn("ddl-b", fio.read(os.path.join(self.p, "banto/drifts/APPLY.md")))
        _w(self.p, "db/b.sql", DDL_B.replace("VARCHAR(200)", "VARCHAR(100)"))
        res = self.sync()
        self.assertEqual(self.drift(res, "users", "email", "length").status, "resolved")
        # 実物がまた食い違ったら、同じ番号で未判断に戻り、以前の判断が経緯に残る
        _w(self.p, "db/b.sql", DDL_B.replace("VARCHAR(200)", "VARCHAR(120)"))
        res = self.sync()
        d3 = self.drift(res, "users", "email", "length")
        self.assertEqual((d3.id, d3.status), (d.id, "open"))
        sheet = fio.read(os.path.join(self.p, "banto/drifts", d.id + ".md"))
        self.assertIn("以前の判断", sheet)

    def test_group_allow(self):
        res = self.sync()
        g = self.drift(res, "users", "id", "unsigned").group
        code, out = _run("--project", self.p, "decide", "--group", g, "--allow", "--value", "×", "--by", "t", "--reason", "方言差")
        self.assertEqual(code, 0, out)
        res = self.sync()
        for c, i in (("users", "id"), ("users", "team_id"), ("teams", "id")):
            self.assertEqual(self.drift(res, c, i, "unsigned").status, "resolved")
        led = fio.read(os.path.join(self.p, "banto/design/detail/tables/users.md"))
        self.assertIn("ddl-b", led.split("## 許容された差")[1])

    def test_existence_allow_and_remove(self):
        res = self.sync()
        d = self.drift(res, "teams", None, "exists")
        self.assertEqual(_run("--project", self.p, "decide", d.id, "--allow", "--value", "あり", "--by", "t", "--reason", "範囲外")[0], 0)
        res = self.sync()
        self.assertEqual(self.drift(res, "teams", None, "exists").status, "resolved")
        # テストの削除の判断 → 仕様書から消すと台帳からも消える
        t = self.drift(res, "UserTests", "Validation#rejectsLongName", "exists")
        self.assertEqual(_run("--project", self.p, "decide", t.id, "--set", "なし", "--by", "t", "--reason", "未実装の計画")[0], 0)
        res = self.sync()
        self.assertEqual(self.drift(res, "UserTests", "Validation#rejectsLongName", "exists").status, "decided")
        _w(self.p, "docs/test-spec.md", SPEC.replace("| `Validation#rejectsLongName()` | 異常系 | 長い名前は拒否 |\n", ""))
        res = self.sync()
        self.assertNotIn("Validation#rejectsLongName", res.ledgers["tests"]["UserTests"].items)

    def test_ledger_hand_edit_creates_drift(self):
        self.sync()
        _set_cell(os.path.join(self.p, "banto/design/detail/tables/users.md"), "`name`", "長さ", "40")  # 設計変更
        res = self.sync()
        d = self.drift(res, "users", "name", "length")
        self.assertEqual(d.status, "open")
        self.assertEqual(d.L, 40)
        self.assertEqual(set(d.deviating), {"doc", "ddl-a", "ddl-b", "jpa"})

    def test_result_follows_authority(self):
        res = self.sync()
        it = res.ledgers["tests"]["UserTests"].items["Validation#rejectsBlankName"]
        self.assertEqual(it.values["result"], "fail")
        _w(self.p, "target/surefire-reports/TEST-x.UserTests.xml", SUREFIRE.replace('<failure type="AssertionError" message="expected"/>', ""))
        res = self.sync()
        self.assertEqual(res.ledgers["tests"]["UserTests"].items["Validation#rejectsBlankName"].values["result"], "pass")

    def test_decide_against_authority_waits_for_rerun(self):
        res = self.sync()
        # 実行結果が fail のテストを「pass が正しい（コードを直す）」と判断する
        it = res.ledgers["tests"]["UserTests"].items["Validation#rejectsBlankName"]
        self.assertEqual(it.values["result"], "fail")
        k = "tests|UserTests|Validation#rejectsBlankName|result"
        res.state.drifts[k] = {"id": "DRF-9000", "status": "open"}
        res.state.save()
        code, out = _run("--project", self.p, "decide", "DRF-9000", "--set", "pass", "--by", "t", "--reason", "バグなので直す")
        self.assertEqual(code, 0, out)
        res = self.sync()
        d = self.drift(res, "UserTests", "Validation#rejectsBlankName", "result")
        self.assertEqual((d.status, d.target, d.deviating), ("decided", "pass", ["surefire"]))
        _w(self.p, "target/surefire-reports/TEST-x.UserTests.xml", SUREFIRE.replace('<failure type="AssertionError" message="expected"/>', ""))
        res = self.sync()
        self.assertEqual(self.drift(res, "UserTests", "Validation#rejectsBlankName", "result").status, "resolved")

    def test_invalid_decisions_are_rejected(self):
        res = self.sync()
        d = self.drift(res, "users", "email", "length")
        code, out = _run("--project", self.p, "decide", d.id, "--set", "abc", "--by", "t", "--reason", "x")
        self.assertNotEqual(code, 0)
        code, out = _run("--project", self.p, "decide", d.id, "--set", "100", "--by", "t")
        self.assertNotEqual(code, 0)   # 理由は必須
        code, out = _run("--project", self.p, "decide", "DRF-9999", "--set", "1", "--by", "t", "--reason", "x")
        self.assertNotEqual(code, 0)


    def test_drift_notes_survive_sync(self):
        res = self.sync()
        d = self.drift(res, "users", "email", "length")
        p = os.path.join(self.p, "banto/drifts", d.id + ".md")
        with open(p, "a", encoding="utf-8") as f:
            f.write("照合係: 200はMySQLだけ。メール長の業務要件を確認したい\n")
        self.sync()
        with open(p, encoding="utf-8") as f:
            self.assertIn("照合係: 200はMySQLだけ", f.read())

    # ------------------------------------------------------------ Excel・レビュー・検査
    def test_export_and_review_roundtrip(self):
        import openpyxl
        self.sync()
        code, out = _run("--project", self.p, "export")
        self.assertEqual(code, 0, out)
        ex = os.path.join(self.p, "banto/export")
        wb = openpyxl.load_workbook(os.path.join(ex, "TD_テーブル定義書.xlsx"))
        self.assertIn("users", wb.sheetnames)
        self.assertTrue(wb["users"].protection.sheet)
        rv = next(f for f in os.listdir(ex) if f.startswith("review-"))
        wb = openpyxl.load_workbook(os.path.join(ex, rv))
        ws = wb["レビュー表"]
        col = next(it.id for it in engine.sync(self.p, write=False).ledgers["tables"]["users"].items.values() if it.name == "email")
        ws["B4"], ws["D4"], ws["F4"], ws["G4"], ws["H4"] = "テーブル定義書", col, "emailは255にしたい", "誤り", "高"
        filled = os.path.join(self.p, "filled.xlsx")
        wb.save(filled)
        code, out = _run("--project", self.p, "import-review", filled)
        self.assertEqual(code, 0, out)
        res = self.sync()
        rv = [d for d in res.drifts if d.domain is None]
        self.assertEqual(len(rv), 1)
        code, out = _run("--project", self.p, "decide", rv[0].id, "--accept", "--target", col, "--attr", "length",
                         "--set", "255", "--by", "t", "--reason", "指摘どおり")
        self.assertEqual(code, 0, out)
        res = self.sync()
        self.assertEqual(res.ledgers["tables"]["users"].items["email"].values["length"], 255)
        self.assertEqual([d for d in res.drifts if d.domain is None][0].status, "resolved")
        self.assertEqual(self.drift(res, "users", "email", "length").status, "decided")

